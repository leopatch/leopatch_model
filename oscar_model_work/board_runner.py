MIB = 1024 * 1024


def crc16(data):
    """CRC-16/CCITT-FALSE (poly 0x1021, init 0xFFFF) -- identical to crc16_ccitt_false() in main.cc."""
    return binascii.crc_hqx(bytes(data), 0xFFFF)


