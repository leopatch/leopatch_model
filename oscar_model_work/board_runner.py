class FakeBoard:
    """Software model of main.cc: same byte protocol, runs the real .tflite on the PC.
    corrupt_every=N flips one payload byte in every Nth window to exercise the CRC / retry path."""

    def __init__(self, tflite, corrupt_every=0):
        self.tflite = Path(tflite)
        self.blob = self.tflite.read_bytes()
        self.it = eh.make_interpreter(self.tflite)
        self.i_d = self.it.get_input_details()[0]
        self.o_d = self.it.get_output_details()[0]
        self.rep = eh.tflite_memory_report(self.tflite)
        self.rx = bytearray()
        self.tx = bytearray()
        self.corrupt_every = corrupt_every
        self.nwin = 0
        self.state = "idle"
        self.need = 0
        self.payload = bytearray()
        self.in_bytes = int(np.prod(self.i_d["shape"]))
        self.tx += b"READY\n"

    # --- serial-like API
    timeout = 1.0

    def reset_input_buffer(self):
        self.tx.clear()

    def write(self, data):
        self.rx += data
        self._pump()
        return len(data)

    def read(self, n=1):
        out = bytes(self.tx[:n])
        del self.tx[:n]
        return out

    def readline(self):
        i = self.tx.find(b"\n")
        if i < 0:
            return b""
        out = bytes(self.tx[: i + 1])
        del self.tx[: i + 1]
        return out

    @property
    def in_waiting(self):
        return len(self.tx)

    def close(self):
        pass

    # --- firmware model
    def _info(self):
        return ("INFO model_bytes=%d model_crc32=%08x arena_size=%d arena_used=%d in_bytes=%d in_zp=%d out_zp=%d "
                "status=ok(simulated)\n" % (len(self.blob), zlib.crc32(self.blob) & 0xFFFFFFFF,
                                           int(self.rep["peak_copy"] * 1.1) + 32768, self.rep["peak_copy"],
                                           self.in_bytes, self.i_d["quantization"][1], self.o_d["quantization"][1]))

    def _pump(self):
        while True:
            if self.state == "idle":
                i = self.rx.find(SYNC)
                if i < 0 or len(self.rx) < i + 3:
                    if i < 0:
                        self.rx = self.rx[-1:]
                    return
                cmd = chr(self.rx[i + 2])
                del self.rx[: i + 3]
                if cmd == "I":
                    self.tx += self._info().encode()
                elif cmd == "W":
                    self.state = "len"
            elif self.state == "len":
                if len(self.rx) < 2:
                    return
                n = self.rx[0] | (self.rx[1] << 8)
                del self.rx[:2]
                if n != self.in_bytes:
                    self.tx += b"ERR len\n"
                    self.state = "idle"
                    continue
                self.need, self.payload, self.state = n, bytearray(), "data"
            elif self.state == "data":
                if not self.rx:
                    return
                take = min(len(self.rx), self.need - len(self.payload), CHUNK - len(self.payload) % CHUNK)
                self.payload += self.rx[:take]
                del self.rx[:take]
                if len(self.payload) % CHUNK == 0 or len(self.payload) == self.need:
                    self.tx += b"K"
                if len(self.payload) == self.need:
                    self.state = "crc"
            elif self.state == "crc":
                if len(self.rx) < 2:
                    return
                want = self.rx[0] | (self.rx[1] << 8)
                del self.rx[:2]
                self.state = "idle"
                self.nwin += 1
                got = bytearray(self.payload)
                if self.corrupt_every and self.nwin % self.corrupt_every == 0:
                    got[17] ^= 0x40                                   # line noise
                if crc16(got) != want:
                    self.tx += b"ERR crc\n"
                    continue
                t0 = time.time()
                self.it.set_tensor(self.i_d["index"], np.frombuffer(bytes(got), np.int8).reshape(self.i_d["shape"]))
                self.it.invoke()
                q = int(self.it.get_tensor(self.o_d["index"]).reshape(-1)[0])
                self.tx += ("RES q=%d ms=%d\n" % (q, int((time.time() - t0) * 1000))).encode()


class Link:
    """Thin wrapper: line-oriented reads with a deadline, on a pyserial port or a FakeBoard."""

    def __init__(self, port):
        self.p = port

    def _read1(self):
        b = self.p.read(1)
        return b if b else None

    def read_until_newline(self, timeout):
        end, buf = time.time() + timeout, bytearray()
        while time.time() < end:
            b = self._read1()
            if b is None:
                continue
            buf += b
            if b == b"\n":
                return buf.decode("ascii", "replace").strip()
        return None

    def wait_prefix(self, prefix, timeout):
        """Read lines until one starts with prefix (or ERR). Returns (line or None)."""
        end = time.time() + timeout
        while time.time() < end:
            ln = self.read_until_newline(max(0.05, end - time.time()))
            if ln is None:
                return None
            if ln.startswith("FAULT"):                       # crash report from the firmware's fault handler
                return "ERR " + ln
            if ln.startswith("READY"):                       # the firmware only says READY at boot
                return "ERR board rebooted during inference (crash?)"
            if ln.startswith(prefix) or ln.startswith("ERR"):
                return ln
        return None

    def wait_byte(self, want, timeout):
        """Wait for a given byte. Returns True, or a string (an ERR line) / None on trouble."""
        end = time.time() + timeout
        while time.time() < end:
            b = self._read1()
            if b is None:
                continue
            if b == want:
                return True
            if b in (b"E",):                                   # "ERR ..." from the firmware
                return "E" + (self.read_until_newline(1.0) or "")
        return None


def open_link(a):
    if a.simulate:
        return Link(FakeBoard(a.tflite, a.sim_corrupt))
    try:
        import serial
    except ImportError:
        sys.exit("pyserial missing: pip install pyserial")
    if not a.port:
        sys.exit("give --port (see `python board_runner.py ports`), or use --simulate")
    p = serial.Serial(a.port, a.baud, timeout=0.05, write_timeout=5, rtscts=a.rtscts)
    time.sleep(0.2)
    p.reset_input_buffer()
    return Link(p)


def get_info(link):
    for _ in range(5):
        link.p.write(SYNC + b"I")
        ln = link.wait_prefix("INFO", 3.0)
        if ln and ln.startswith("INFO"):
            return dict(kv.split("=", 1) for kv in ln.split()[1:] if "=" in kv)
        time.sleep(0.2)
    return None


def send_window(link, q, infer_timeout):
    """One window. Returns (q_out, ms) or raises RuntimeError(reason)."""
    data = bytes(q.astype(np.int8).tobytes())
    n = len(data)
    link.p.write(SYNC + b"W" + bytes([n & 255, n >> 8]))
    for off in range(0, n, CHUNK):
        link.p.write(data[off:off + CHUNK])
        r = link.wait_byte(b"K", 3.0)
        if r is not True:
            raise RuntimeError(r if isinstance(r, str) else "no chunk ack (timeout)")
    c = crc16(data)
    link.p.write(bytes([c & 255, c >> 8]))
    ln = link.wait_prefix("RES", infer_timeout)
    if ln is None:
        raise RuntimeError("no RES line (inference timeout)")
    if not ln.startswith("RES"):
        raise RuntimeError(ln)
    m = re.match(r"RES q=(-?\d+) ms=(\d+)", ln)
    if not m:
        raise RuntimeError("bad RES line: " + ln)
    return int(m.group(1)), int(m.group(2))


# ======================================================================================
# build-log parser: flash / RAM used by the whole firmware
# ======================================================================================
def parse_build_log(path):
    """Zephyr prints 'Memory region  Used Size  Region Size  %age Used' after linking."""
    unit = {"B": 1, "KB": 1024, "MB": MIB}
    out = {}
    for ln in Path(path).read_text(errors="replace").splitlines():
        m = re.match(r"\s*([A-Za-z0-9_]+):\s+(\d+)\s+(B|KB|MB)\s+(\d+)\s+(B|KB|MB)\s+([\d.]+)%", ln)
        if m and m.group(1) != "IDT_LIST":
            out[m.group(1)] = {"used": int(m.group(2)) * unit[m.group(3)], "size": int(m.group(4)) * unit[m.group(5)]}
    return out


