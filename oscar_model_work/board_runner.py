#!/usr/bin/env python3
"""
board_runner.py  --  script 2 of 2.  Run the int8 ECG sex model ON the nRF54LM20 DK and score it.

The model runs on the board's Cortex-M33 CPU with TensorFlow Lite Micro (not the Axon NPU).
This script (on your computer) streams real ECG windows to the board over the DK's USB virtual COM
port, reads back the int8 logit and the inference time, and compares with what the same windows give
on the computer (fp32 and int8).  It reports:
  * accuracy / AUC / sensitivity / specificity of the model as it runs ON THE BOARD
  * how closely the board reproduces the PC int8 result (the real test that the port is correct)
  * latency per ECG, flash and RAM actually used (board-reported arena + the firmware build log)

Steps (details in board_fw/README.md):
  1.  python board_runner.py prepare                 # bakes the .tflite into board_fw/src/model_data.cc
  2.  west build / west flash  the folder board_fw   # see README
  3.  python board_runner.py ports                   # find the DK's COM port
  4.  python board_runner.py run --port <PORT> --n 20 --build-log build.log
  Without a board:  python board_runner.py run --simulate --n 40       # tests this script + the protocol

Needs: numpy, pyserial (pip install pyserial), and for the PC reference: tensorflow or ai-edge-litert.
"""
