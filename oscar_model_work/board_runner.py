def pick_subset(y, n, seed=0):
    """Class-balanced random subset of the board set, deterministic."""
    r = np.random.default_rng(seed)
    pos, neg = np.flatnonzero(y == 1), np.flatnonzero(y == 0)
    k = n // 2
    sel = np.concatenate([r.choice(pos, min(k, len(pos)), replace=False),
                          r.choice(neg, min(n - k, len(neg)), replace=False)])
    r.shuffle(sel)
    return sel


def cmd_run(a):
    bs = np.load(a.boardset)
    X, y, fp32 = bs["x"], bs["y"].astype(int), bs["fp32_logit"].astype(np.float64)
    patient, thr = bs["patient"], float(bs["threshold"])
    sel = pick_subset(y, min(a.n, len(y)))
    n = len(sel)

    it = eh.make_interpreter(a.tflite)
    i_d, o_d = it.get_input_details()[0], it.get_output_details()[0]
    (i_s, i_zp), (o_s, o_zp) = i_d["quantization"], o_d["quantization"]
    Xq = np.clip(np.round(X[sel] / i_s + i_zp), -128, 127).astype(np.int8)
    pc_logit, pc_q = eh.eval_tflite(a.tflite, X[sel])           # same int8 model on the PC
    blob_crc = zlib.crc32(Path(a.tflite).read_bytes()) & 0xFFFFFFFF

    print(f"opening {'SIMULATED board' if a.simulate else a.port} ...")
    link = open_link(a)
    info = get_info(link)
    if info is None:
        sys.exit("The board did not answer. Check: firmware flashed? right COM port (the DK has two)? "
                 "Press the DK's reset button and retry. See board_fw/README.md > Troubleshooting.")
    print("board says:", info)
    problems = []
    if info.get("status", "").split("(")[0] != "ok":
        problems.append(f"model setup failed on the board: status={info.get('status')} -- see README troubleshooting")
    if info.get("model_crc32") and int(info["model_crc32"], 16) != blob_crc:
        problems.append(f"model on the board (crc {info['model_crc32']}) is NOT the .tflite you pass here "
                        f"(crc {blob_crc:08x}) -- run `prepare` again and reflash")
    if info.get("in_zp") and int(info["in_zp"]) != int(i_zp):
        problems.append(f"input zero point differs: board {info['in_zp']} vs file {i_zp}")
    if problems:
        sys.exit("STOP:\n  " + "\n  ".join(problems))

    qb = np.full(n, 127, np.int16)
    ms = np.zeros(n)
    ok = np.zeros(n, bool)
    errors = []
    t_start = time.time()
    for k in range(n):
        for attempt in range(a.retries + 1):
            try:
                qb[k], ms[k] = send_window(link, Xq[k], a.infer_timeout)
                ok[k] = True
                break
            except RuntimeError as e:
                errors.append((k, attempt, str(e)))
                print(f"   window {k}: {e}  (attempt {attempt + 1}/{a.retries + 1})")
                # after a CRC/length complaint the board is already back in its main loop; after a timeout it
                # may still be waiting for bytes (its longest rx timeout is 2 s), so let it finish first
                time.sleep(0.3 if str(e).startswith(("ERR crc", "ERR len")) else 2.6)
                link.p.reset_input_buffer()
        if k == 0 and ok[0]:
            print(f" first inference took {ms[0]:.0f} ms on the board "
                  f"-> all {n} windows ~ {n * (ms[0] / 1000 + 0.6) / 60:.1f} min")
        elif (k + 1) % 5 == 0 or k + 1 == n:
            print(f" {k + 1}/{n} windows  ({time.time() - t_start:.0f}s)", flush=True)
    link.p.close()

    good = np.flatnonzero(ok)
    if len(good) == 0:
        sys.exit("no window was processed successfully")
    ys = y[sel][good]
    b_logit = (qb[good].astype(np.float32) - o_zp) * o_s
    pcl, p_q = pc_logit[good], pc_q[good]
    f32 = fp32[sel][good]

    # --- how well does the board reproduce the PC int8 model?
    dq = qb[good].astype(int) - p_q.astype(int)
    pred = lambda s: eh.sigmoid(s) >= thr                       # noqa: E731
    agree_pc = float((pred(b_logit) == pred(pcl)).mean())
    agree_f32 = float((pred(b_logit) == pred(f32)).mean())
    # --- model quality as seen on the board
    mb = eh.point_metrics(ys, b_logit, thr)
    mp = eh.point_metrics(ys, pcl, thr)
    mf = eh.point_metrics(ys, f32, thr)
    boot = None
    if len(good) >= 20:
        bt = eh.patient_bootstrap(patient[sel][good], ys, {"board": b_logit}, thr, 300)
        boot = {"auc": eh.ci(bt["board"]["auc"]), "acc": eh.ci(bt["board"]["acc"])}

    lat = ms[good]
    res = {"n_windows": int(n), "n_ok": int(len(good)), "n_errors_logged": len(errors), "threshold": thr,
           "board_info": info, "metrics_board": mb, "metrics_pc_int8": mp, "metrics_pc_fp32": mf,
           "ci95_board": boot, "agree_decision_vs_pc_int8": agree_pc, "agree_decision_vs_fp32": agree_f32,
           "exact_q_match": float((dq == 0).mean()), "mean_abs_dq": float(np.abs(dq).mean()),
           "max_abs_dq": int(np.abs(dq).max()),
           "latency_ms": {"mean": float(lat.mean()), "median": float(np.median(lat)),
                          "p95": float(np.percentile(lat, 95)), "max": float(lat.max())},
           "simulated": bool(a.simulate), "board_q": qb[good].tolist(), "pc_q": p_q.astype(int).tolist(),
           "label": ys.tolist(), "ms": lat.tolist()}

    arena_used = int(info.get("arena_used", 0))
    mem = {"model_bytes_in_flash": int(info.get("model_bytes", 0)), "tflm_arena_used": arena_used,
           "tflm_arena_reserved": int(info.get("arena_size", 0))}
    if a.build_log:
        mem["build_log"] = parse_build_log(a.build_log)
    res["memory"] = mem

    pct = lambda v: f"{v * 100:.1f}%"                           # noqa: E731
    print("\n" + "=" * 78)
    print(" RESULT" + ("  (SIMULATED board -- this tested the script, not the hardware)" if a.simulate else ""))
    print("=" * 78)
    print(f" windows scored on the board : {len(good)}/{n}   (balanced real test ECGs, lead V3)")
    print(f" threshold                    : p >= {thr:.4f}  (chosen on the validation set)")
    print(f"\n {'':16s}{'accuracy':>10s}{'AUC':>9s}{'sens':>8s}{'spec':>8s}")
    for nm, m in (("fp32 (PC)", mf), ("int8 (PC)", mp), ("int8 ON BOARD", mb)):
        print(f" {nm:16s}{pct(m['acc']):>10s}{m['auc']:>9.4f}{pct(m['sens']):>8s}{pct(m['spec']):>8s}")
    if boot:
        print(f" board 95% CI (patient bootstrap, {len(good)} windows -- wide!): "
              f"acc [{boot['acc'][0] * 100:.0f}, {boot['acc'][1] * 100:.0f}]%  AUC [{boot['auc'][0]:.2f}, {boot['auc'][1]:.2f}]")
        print(" (a few dozen windows only show the port works; the full-test-set number comes from eval_host.py)")
    print(f"\n port correctness: board output == PC int8 output on {pct(res['exact_q_match'])} of windows, "
          f"mean |dq| = {res['mean_abs_dq']:.2f}, max |dq| = {res['max_abs_dq']} (int8 steps)")
    print(f"                   same male/female decision as PC int8: {pct(agree_pc)};  as fp32: {pct(agree_f32)}")
    if res["max_abs_dq"] > 3:
        print("   WARNING: differences above a few int8 steps are not rounding noise -- suspect an op/version/layout mismatch.")
    print(f"\n latency per ECG on the board: mean {lat.mean():.0f} ms, median {np.median(lat):.0f}, "
          f"p95 {np.percentile(lat, 95):.0f}, max {lat.max():.0f}")
    print("\n MEMORY")
    print(f"  model weights (flash)       : {mem['model_bytes_in_flash']:,} B = {mem['model_bytes_in_flash'] / 1024:.0f} KiB")
    print(f"  TFLM arena actually needed  : {arena_used:,} B = {arena_used / 1024:.0f} KiB (reserved {mem['tflm_arena_reserved'] / 1024:.0f} KiB)")
    if a.build_log:
        for region, v in mem["build_log"].items():
            print(f"  whole firmware, {region:6s}      : {v['used']:,} B of {v['size']:,} B  ({v['used'] / v['size'] * 100:.1f}%)")
    else:
        print("  (pass --build-log build.log to also show total flash/RAM of the firmware image)")
    if errors:
        print(f"\n {len(errors)} transfer error(s) were retried, e.g. {errors[0]}")
    out = Path(a.out) if a.out else HERE / "export_out" / ("board_results_SIM.json" if a.simulate else "board_results_leadv3.json")
    out.parent.mkdir(exist_ok=True)
    out.write_text(json.dumps(res, indent=2))
    print(f"\n saved: {out}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sp = sub.add_parser("ports", help="list serial ports")
    sp.set_defaults(fn=cmd_ports)
    sp = sub.add_parser("prepare", help="generate board_fw/src/model_data.cc + model_config.h from the .tflite")
    sp.add_argument("--tflite", default=str(DEFAULT_TFLITE))
    sp.add_argument("--arena-kib", type=int, default=0, help="override the TFLM arena size (KiB)")
    sp.set_defaults(fn=cmd_prepare)
    sp = sub.add_parser("run", help="stream test ECGs to the board and score the answers")
    sp.add_argument("--port", help="e.g. /dev/cu.usbmodem0010501234561 or COM7")
    sp.add_argument("--baud", type=int, default=115200)
    sp.add_argument("--rtscts", action="store_true", help="enable hardware flow control (try if the board never answers)")
    sp.add_argument("--tflite", default=str(DEFAULT_TFLITE))
    sp.add_argument("--boardset", default=str(DEFAULT_BOARDSET))
    sp.add_argument("--n", type=int, default=20, help="number of windows (balanced). Start small: see README on speed")
