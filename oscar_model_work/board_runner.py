# prepare: .tflite -> C arrays + sizes
# ======================================================================================
def cmd_prepare(a):
    tfl = Path(a.tflite)
    blob = tfl.read_bytes()
    rep = eh.tflite_memory_report(tfl)
    it = eh.make_interpreter(tfl)
    in_bytes = int(np.prod(it.get_input_details()[0]["shape"]))
    if a.arena_kib:
        arena = a.arena_kib * 1024
    else:                                           # estimated peak + 10% + 32 KiB (TFLM bookkeeping, scratch)
        arena = int(rep["peak_copy"] * 1.10) + 32 * 1024
    arena = (arena + 15) // 16 * 16

    FW_SRC.mkdir(parents=True, exist_ok=True)
    (FW_SRC / "model_config.h").write_text(
        "/* generated by board_runner.py prepare -- do not edit */\n"
        "#pragma once\n#include <stddef.h>\n\n"
        f"#define MODEL_ARENA_BYTES {arena}u   /* raise if the board reports status=alloc_fail_raise_arena */\n"
        f"#define MODEL_INPUT_BYTES {in_bytes}u\n\n"
        "extern const unsigned char g_model_data[];\nextern const unsigned int g_model_len;\n")
    lines = []
    for i in range(0, len(blob), 16):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in blob[i:i + 16]) + ",")
    (FW_SRC / "model_data.cc").write_text(
        "/* generated by board_runner.py prepare from " + tfl.name + " -- do not edit */\n"
        '#include "model_config.h"\n\n'
        "alignas(16) const unsigned char g_model_data[] = {\n" + "\n".join(lines) + "\n};\n"
        f"const unsigned int g_model_len = {len(blob)}u;\n")
    print(f"wrote {FW_SRC / 'model_data.cc'}  ({len(blob):,} bytes of model)")
    print(f"wrote {FW_SRC / 'model_config.h'}  (arena {arena:,} B = {arena / 1024:.0f} KiB, input {in_bytes} B)")
    print(f"model CRC32 the board should report: {zlib.crc32(blob) & 0xFFFFFFFF:08x}")
    print(f"estimated activation peak: {rep['peak_alias'] / 1024:.0f}-{rep['peak_copy'] / 1024:.0f} KiB")
    print("next: build and flash board_fw (README.md)")


