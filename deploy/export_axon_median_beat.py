#!/usr/bin/env python3
# Export the 800-sample median-beat ECG sex classifier for the nRF54LM20B Axon NPU.
#
# Same layers as the 10 s model (ECGSexClassifier), but the input is one 800-sample median beat,
# so every tensor already fits the NPU's 1024 limit. The split is:
#   front end (Cortex-M33 CPU, float): z-score + stem conv + BN + ReLU + max-pool -> 64 x 200
#   NPU part (int8 TFLite -> Axon compiler): layer1 ... fc
# TF's SAME padding puts the odd pad sample at the end, PyTorch pads both sides equally. For the
# stride-2 convs, a zero tap appended to the kernel (7 -> 8 taps) makes SAME pad 3 on each side,
# so the NPU math is identical to PyTorch. The max-pool has no such trick, so it stays on the CPU.
#
# Usage (from the repo root, inside the axon venv):
#   python deploy/export_axon_median_beat.py --calib-npy calib_beats.npy \
#       --eval-npy eval_beats.npy --eval-labels-npy eval_labels.npy
# where the .npy files hold (N, 800) median beats (male = 1 in the labels).

import argparse
import os
import shutil
import sys
from pathlib import Path

import numpy as np
import torch

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")
import tensorflow as tf  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
from export_axon_model import (ECGSexClassifier, Int8Runner, c_floats, convert_int8,  # noqa: E402
                               fold_bn, preprocess, run_axon_compiler, sigmoid, tf_kernel)

REPO = Path(__file__).resolve().parent.parent
BEAT_LEN = 800
STEM_OUT = 400
POOL_OUT = 200
NPU_C = 64


def build_params(model):
    stem_w, stem_b = fold_bn(model.stem[0], model.stem[1])
    p = {}
    for name, conv, bn, stride2 in [
        ("layer1", model.layer1[0], model.layer1[1], True),
        ("res1_c1", model.res1.conv1, model.res1.bn1, False),
        ("res1_c2", model.res1.conv2, model.res1.bn2, False),
        ("layer2", model.layer2[0], model.layer2[1], True),
        ("res2_c1", model.res2.conv1, model.res2.bn1, False),
        ("res2_c2", model.res2.conv2, model.res2.bn2, False),
    ]:
        w, b = fold_bn(conv, bn)
        if stride2:
            w = np.concatenate([w, np.zeros_like(w[:, :, :1])], axis=2)   # 7 -> 8 taps, see header
        p[name + "_w"], p[name + "_b"] = tf_kernel(w), b
    for name, lin in [("fc1", model.fc[1]), ("fc2", model.fc[3])]:
        p[name + "_w"] = np.ascontiguousarray(lin.weight.detach().numpy().T)
        p[name + "_b"] = lin.bias.detach().numpy().copy()
    return stem_w[:, 0, :], stem_b, p


# Front end (mirrored in firmware/leopatch_onchip/src/frontend.c)
# -------------------------------------------------------------------------
def frontend(x, stem_w, stem_b):
    """Normalized beats (N, 800) -> NPU input (N, 64, 200): stem + ReLU + max-pool."""
    idx = 2 * np.arange(STEM_OUT)[:, None] + np.arange(15)[None, :]
    xp = np.pad(x, ((0, 0), (7, 7)))
    z = np.einsum("ntk,ck->nct", xp[:, idx], stem_w) + stem_b[None, :, None]
    # ReLU output is >= 0, so zero padding is equivalent to MaxPool1d's -inf padding
    zp = np.pad(np.maximum(z, 0), ((0, 0), (0, 0), (1, 1)))
    return np.maximum(np.maximum(zp[:, :, 0:2 * POOL_OUT:2], zp[:, :, 1:2 * POOL_OUT + 1:2]),
                      zp[:, :, 2:2 * POOL_OUT + 2:2]).astype(np.float32)


def to_nhwc(P):
    return np.ascontiguousarray(P.transpose(0, 2, 1)[:, None, :, :])


class NpuPart(tf.Module):
    def __init__(self, params):
        super().__init__()
        self.p = {k: tf.constant(v) for k, v in params.items()}

    def forward(self, x):
        p = self.p

        def conv(x, name, stride=1):
            y = tf.nn.conv2d(x, p[name + "_w"], strides=[1, 1, stride, 1], padding="SAME")
            return tf.nn.bias_add(y, p[name + "_b"])

        x = tf.nn.relu(conv(x, "layer1", stride=2))                 # 200 -> 100
        x = tf.nn.relu(conv(tf.nn.relu(conv(x, "res1_c1")), "res1_c2") + x)
        x = tf.nn.relu(conv(x, "layer2", stride=2))                 # 100 -> 50
        x = tf.nn.relu(conv(tf.nn.relu(conv(x, "res2_c1")), "res2_c2") + x)
        x = tf.reduce_mean(x, axis=[1, 2])                          # global average pool over 50
        x = tf.nn.relu(tf.matmul(x, p["fc1_w"]) + p["fc1_b"])
        return tf.matmul(x, p["fc2_w"]) + p["fc2_b"]

    @tf.function(input_signature=[tf.TensorSpec([1, 1, POOL_OUT, NPU_C], tf.float32)])
    def single(self, x):
        return self.forward(x)

    @tf.function(input_signature=[tf.TensorSpec([None, 1, POOL_OUT, NPU_C], tf.float32)])
    def batched(self, x):
        return self.forward(x)


def write_frontend_header(path, stem_w, stem_b):
    rows = ",\n".join("\t{" + c_floats(r, 15).strip() + "}" for r in stem_w)
    path.write_text(
        "/* Generated by deploy/export_axon_median_beat.py: stem conv with BatchNorm folded in. */\n"
        "#pragma once\n\n"
        "#define FRONTEND_STEM_CHANNELS 64\n#define FRONTEND_STEM_KERNEL 15\n\n"
        f"static const float frontend_stem_w[64][15] = {{\n{rows}\n}};\n\n"
        f"static const float frontend_stem_b[64] = {{\n{c_floats(stem_b)}\n}};\n")


def write_test_header(path, beats, ref_float, ref_int8, threshold):
    body = ",\n".join("{\n" + c_floats(r, 10) + "\n}" for r in beats)
    path.write_text(
        f"/* Generated by deploy/export_axon_median_beat.py: {len(beats)} PTB-XL median beats. */\n"
        "#pragma once\n\n"
        f"#define TEST_BEAT_COUNT {len(beats)}\n#define TEST_BEAT_LEN {BEAT_LEN}\n\n"
        "/* Decision threshold on sigmoid(logit): above it means male. */\n"
        f"#define MODEL_THRESHOLD {threshold:.6f}f\n\n"
        f"static const float test_beat[TEST_BEAT_COUNT][TEST_BEAT_LEN] = {{\n{body}\n}};\n\n"
        "/* Expected logits: PyTorch float model and int8 TFLite reference. */\n"
        f"static const float test_beat_logit_float[TEST_BEAT_COUNT] = {{\n{c_floats(ref_float)}\n}};\n"
        f"static const float test_beat_logit_int8[TEST_BEAT_COUNT] = {{\n{c_floats(ref_int8)}\n}};\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--checkpoint", type=Path,
                    default=REPO / "models/2026.10.28/best_leadv3_median_beat_w800_sweep.pth")
    ap.add_argument("--calib-npy", type=Path, required=True, help="(N, 800) median beats")
    ap.add_argument("--eval-npy", type=Path, required=True, help="(N, 800) median beats, held out")
    ap.add_argument("--eval-labels-npy", type=Path, required=True, help="(N,) male = 1")
    ap.add_argument("--threshold", type=float, default=0.89,
                    help="decision threshold; 0.89 is the best PTB-XL patch-lead cutoff until the "
                         "training val_threshold for this model is available")
    ap.add_argument("--n-firmware", type=int, default=4, help="test beats embedded in the firmware")
    ap.add_argument("--model-name", default="ecg_sex_beat")
    ap.add_argument("--out-dir", type=Path, default=REPO / "deploy/out_beat")
    ap.add_argument("--firmware-dir", type=Path, default=REPO / "firmware/leopatch_onchip/src/generated")
    ap.add_argument("--addon-dir", type=Path,
                    default=Path(os.environ.get("EDGE_AI_ADDON_DIR", "/opt/nordic/ncs/sdk-edge-ai")))
    ap.add_argument("--il-buffer", type=int, default=200000, help="Axon interlayer buffer upper bound")
    ap.add_argument("--skip-compile", action="store_true")
    args = ap.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    args.firmware_dir.mkdir(parents=True, exist_ok=True)

    model = ECGSexClassifier(in_channels=1)
    model.load_state_dict(torch.load(args.checkpoint, map_location="cpu", weights_only=True))
    model.eval()
    calib = preprocess(np.load(args.calib_npy))
    ev = preprocess(np.load(args.eval_npy))
    y = np.load(args.eval_labels_npy)
    assert calib.shape[1] == ev.shape[1] == BEAT_LEN

    # 1) split model, check the float rewrite matches PyTorch
    stem_w, stem_b, params = build_params(model)
    npu = NpuPart(params)
    with torch.no_grad():
        torch_logit = model(torch.from_numpy(ev[:, None, :])).numpy()[:, 0]
    P_ev = to_nhwc(frontend(ev, stem_w, stem_b))
    split_logit = np.concatenate([npu.batched(P_ev[i:i + 64]).numpy()[:, 0] for i in range(0, len(ev), 64)])
    err = np.abs(split_logit - torch_logit).max()
    print(f"Float split model vs PyTorch: logit max err {err:.2e}")
    if err > 1e-3:
        sys.exit("Split model does not match PyTorch, aborting.")

    # 2) int8 quantization, calibrated on the calibration beats
    tfl = convert_int8(npu, to_nhwc(frontend(calib, stem_w, stem_b)))
    tflite_path = args.out_dir / f"{args.model_name}_npu_int8.tflite"
    tflite_path.write_bytes(tfl)
    runner = Int8Runner(tfl)
    P_q = runner.quantize(P_ev)
    int8_logit = np.array([runner(q) for q in P_q])
    p_f, p_q = sigmoid(torch_logit), sigmoid(int8_logit)
    from sklearn.metrics import roc_auc_score
    print(f"int8 TFLite ({len(tfl) / 1024:.0f} KB) vs PyTorch on {len(ev)} held-out beats:")
    print(f"  logit max err {np.abs(int8_logit - torch_logit).max():.3f}, "
          f"corr {np.corrcoef(int8_logit, torch_logit)[0, 1]:.4f}")
    print(f"  same decision at threshold {args.threshold:.2f}: "
          f"{np.mean((p_q >= args.threshold) == (p_f >= args.threshold)):.1%}")
    print(f"  AUC float {roc_auc_score(y, p_f):.4f} | int8 {roc_auc_score(y, p_q):.4f}")

    # 3) artifacts: compiler test vectors, firmware headers
    test_q_path = args.out_dir / f"{args.model_name}_test_q.npy"
    np.save(test_q_path, P_q[:8])
    fw = np.arange(args.n_firmware)
    write_frontend_header(args.firmware_dir / "frontend_params.h", stem_w, stem_b)
    write_test_header(args.firmware_dir / "test_beats.h", ev[fw], torch_logit[fw], int8_logit[fw],
                      args.threshold)
    print(f"Wrote {tflite_path.relative_to(REPO)} and firmware headers in {args.firmware_dir.relative_to(REPO)}")

    if args.skip_compile:
        return
    rc = run_axon_compiler(args.addon_dir, args.out_dir, args.model_name, tflite_path, test_q_path,
                           args.il_buffer)
    header = args.out_dir / "outputs" / f"nrf_axon_model_{args.model_name}_.h"
    if rc == 0 and header.exists():
        shutil.copy(header, args.firmware_dir / header.name)
        print(f"Copied {header.name} to {args.firmware_dir.relative_to(REPO)}")
    sys.exit(rc)


if __name__ == "__main__":
    main()
